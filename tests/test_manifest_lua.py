"""Comment-aware Lua parsing: the highest-risk logic in the manifest path.

A naive regex scan of Hubcap's Lua injects depots the generator deliberately
disabled, and misreads keyless addappid() calls as DLCs. Every case below is a
real shape produced by the generator.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from uran_backend import manifest_lua as ml

fails = []


def check(label, got, want):
    if got != want:
        fails.append(f"FAIL {label}\n     got  {got!r}\n     want {want!r}")
    else:
        print(f"ok  {label}")


KEY_A = "a" * 64
KEY_B = "b" * 64
KEY_C = "c" * 64

LIVE = f"""
-- Generated by Hubcap
addappid(620, 1, "{KEY_A}") -- Portal 2
addappid(621, 1, "{KEY_B}") -- Portal 2 win64 depot
addappid(4000) -- License only DLC
setManifestid(621, "1234567890123456789")
"""

r = ml.parse(LIVE, lambda k: k)
check("first addappid is the app", r["appid"], "620")
check("game name from trailing comment", r["name"], "Portal 2")
check("app key captured", r["keys"].get("620"), KEY_A)
check("depot key captured", r["keys"].get("621"), KEY_B)
check("keyless addappid is a DLC", r["dlcs"], ["4000"])
check("manifest id parsed", r["manifests"], {"621": "1234567890123456789"})
check("DLC is not treated as a depot", "4000" in r["depots"], False)

# --- commented-out statements must be invisible -------------------------
COMMENTED = f"""
-- addappid(9999, 1, "{KEY_C}") -- depot Hubcap cannot serve
-- addappid(8888) -- empty depot
addappid(620, 1, "{KEY_A}") -- Portal 2
"""
r = ml.parse(COMMENTED, lambda k: k)
check("commented addappid yields no key", "9999" in r["keys"], False)
check("commented addappid yields no depot", "9999" in r["depots"], False)
check("commented keyless is not a DLC", "8888" in r["dlcs"], False)
check("commented appid does not become the app", r["appid"], "620")

# --- MISSING_KEY sentinel ----------------------------------------------
MISSING = f"""
addappid(620, 1, "{KEY_A}") -- Portal 2
-- addappid(7777, 1, "MISSING_KEY")
addappid(6666, 1, "MISSING_KEY") -- sentinel inline
addappid(5555, 1, "0") -- zero sentinel
"""
r = ml.parse(MISSING, lambda k: k)
check("MISSING_KEY is not a key", "6666" in r["keys"], False)
check("MISSING_KEY is not a depot", "6666" in r["depots"], False)
check("zero sentinel is not a key", "5555" in r["keys"], False)

# --- a '--' inside a string is not a comment ---------------------------
TRICKY = f'''
addappid(620, 1, "{KEY_A}") -- real comment
-- setManifestid(7000, "111")
setManifestid(620, "999888777666555444")
'''
r = ml.parse(TRICKY, lambda k: k)
check("commented setManifestid ignored", "7000" in r["manifests"], False)
check("live setManifestid kept", r["manifests"].get("620"), "999888777666555444")

# --- sanitize_key rejection --------------------------------------------
# The root AppKey (first addappid) is NOT passed through sanitize_key — ASSella
# treats it the same way. It is still validated downstream: _inject_sls_config
# runs every key through sanitize_key and skips anything malformed.
r = ml.parse(LIVE, lambda k: None)
check("rejected depot keys are dropped", "621" in r["keys"], False)
check("root AppKey bypasses sanitize (ASSella parity)", "620" in r["keys"], True)

# --- id coercion blocks path injection ----------------------------------
check("coerce_depot_id rejects traversal", ml.coerce_depot_id("../../../etc/passwd"), None)
check("coerce_depot_id rejects bool", ml.coerce_depot_id(True), None)
check("coerce_depot_id accepts digits", ml.coerce_depot_id("620"), "620")
check("coerce_manifest_gid rejects junk", ml.coerce_manifest_gid("a/b"), None)

# --- placeholder detection ---------------------------------------------
check("empty is placeholder", ml.is_placeholder_key(""), True)
check("MISSING_KEY is placeholder", ml.is_placeholder_key("MISSING_KEY"), True)
check("quoted placeholder is placeholder", ml.is_placeholder_key('"NULL"'), True)
check("real key is not placeholder", ml.is_placeholder_key(KEY_A), False)

# --- depot name harvesting ---------------------------------------------
HARVEST = f"""
addappid(620, 1, "{KEY_A}") -- Portal 2
addappid(621, 1, "{KEY_B}") -- Portal 2 win64
-- addappid(9999, 1, "{KEY_C}") -- Disabled Depot
"""
cache = {}
found = ml.harvest_depot_names(HARVEST, cache, lambda s: s)
check("harvest finds live names", cache.get("621"), "Portal 2 win64")
check("harvest skips commented", "9999" in cache, False)
check("harvest counts", found, 2)

print()
if fails:
    print("\n".join(fails))
    sys.exit(1)
print("all Lua parsing checks pass")